"""Synthetic stand-in for M1's outputs, so M2 can be built and tested first.

Why: the route planner needs the four C2 rasters, ``samples.geojson`` (C3) and
``hazard_model.json``. Until M1's pipeline has run, this writes fake versions
with the exact C2 grid geometry (2133 × 1007, 5 m, ``ESRI:103885``, float32,
NaN NoData) into a separate directory tree with the repo layout. Point the API
at it with ``MARS_ODYSSEY_ROOT=<out_dir>``.

The terrain is a gentle tilt plus Gaussian hills and a steep crater rim, so the
three route profiles really do diverge. The numbers mean nothing physically;
``data/STUB_DATA`` marks the tree as fake so data-dependent tests can skip.

Usage: ``python -m backend.tools.make_stub_data <out_dir>``
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import numpy as np
import rasterio
from rasterio.transform import Affine
from scipy.ndimage import gaussian_filter

from backend.services.terrain import MARS_RADIUS_M, RASTER_PATHS

# ---------------------------------------------------------------- configuration (C2)
ROWS, COLS = 1007, 2133
TRANSFORM = Affine(5.0, 0.0, 4581341.0, 0.0, -5.0, 1096879.0)
CRS = "ESRI:103885"
SEED = 7
DEMO_START = (77.45088572, 18.44462715)    # landing site (C4)
DEMO_END = (77.3052, 18.4975)              # Cheyava Falls / sample 25 (C4)

HAZARD_MODEL = {
    "formula": "STUB: (0.4·slope_risk + 0.3·roughness_risk) / 0.7",
    "weights": {"slope": 0.4, "roughness": 0.3, "obstacle": 0.2, "crater": 0.1},
    "factor_available": {"slope": True, "roughness": True, "obstacle": False, "crater": False},
    "model_weight_coverage": 0.7,
    "renormalised": True,
    "slope_stops": [[0, 5, 15, 25, 30], [0, 10, 50, 90, 100]],
    "roughness_stops": [[0, 0.1, 0.25, 0.5], [0, 25, 60, 100]],
    "no_go_slope_deg": 30,
    "classes": [{"min": 0, "max": 20, "label": "Low"}, {"min": 20, "max": 40, "label": "Moderate"},
                {"min": 40, "max": 60, "label": "Elevated"}, {"min": 60, "max": 80, "label": "High"},
                {"min": 80, "max": 100, "label": "Severe"}],
    "class_fraction": {}, "no_go_fraction": 0.0,
    "disclaimer": "STUB DATA generated by backend/tools/make_stub_data.py, not M1's model.",
}


def _grid_lonlat() -> tuple[np.ndarray, np.ndarray]:
    x = TRANSFORM.c + (np.arange(COLS) + 0.5) * TRANSFORM.a
    y = TRANSFORM.f + (np.arange(ROWS) + 0.5) * TRANSFORM.e
    lon, lat = np.degrees(x / MARS_RADIUS_M), np.degrees(y / MARS_RADIUS_M)
    return np.meshgrid(lon, lat)


def make_terrain(rng: np.random.Generator) -> dict[str, np.ndarray]:
    lon, lat = _grid_lonlat()
    yy, xx = np.mgrid[0:ROWS, 0:COLS] * 5.0                  # metres from the NW corner
    z = -2600.0 + 0.01 * xx + 0.005 * yy                     # gentle tilt
    for _ in range(150):                                     # hills, some steep
        cy, cx = rng.uniform(0, ROWS * 5), rng.uniform(0, COLS * 5)
        h, s = rng.uniform(15, 80), rng.uniform(40, 220)
        z += h * np.exp(-((yy - cy) ** 2 + (xx - cx) ** 2) / (2 * s ** 2))
    cy, cx = ROWS * 5 * 0.45, COLS * 5 * 0.55                # crater with a steep rim
    rr = np.hypot(yy - cy, xx - cx)
    z += 45 * np.exp(-((rr - 500) / 25) ** 2) - 60 * np.exp(-(rr / 400) ** 2)
    z = z.astype(np.float32)

    dx = 5.0 * np.cos(np.radians(lat))
    dzdy, dzdx = np.gradient(z, 5.0, axis=0), np.gradient(z, axis=1) / dx
    slope = np.degrees(np.arctan(np.hypot(dzdx, dzdy))).astype(np.float32)
    rough = gaussian_filter(np.abs(rng.normal(0, 0.15, z.shape)), 3) * 3 + slope / 200
    rough = rough.astype(np.float32)

    s_x, s_y = HAZARD_MODEL["slope_stops"]
    r_x, r_y = HAZARD_MODEL["roughness_stops"]
    hazard = ((0.4 * np.interp(slope, s_x, s_y) + 0.3 * np.interp(rough, r_x, r_y)) / 0.7)
    hazard = hazard.astype(np.float32)

    for arr in (z, slope, rough, hazard):                    # a NoData strip on the edge
        arr[:, :3] = np.nan
    return {"elevation": z, "slope": slope, "roughness": rough, "hazard": hazard}


def _write_tif(path: Path, arr: np.ndarray) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with rasterio.open(path, "w", driver="GTiff", height=ROWS, width=COLS, count=1,
                       dtype="float32", crs=CRS, transform=TRANSFORM, nodata=np.nan,
                       compress="deflate") as ds:
        ds.write(arr, 1)


def make_samples(rng: np.random.Generator, z: np.ndarray) -> dict:
    lon, lat = _grid_lonlat()
    pts = [(rng.uniform(77.30, 77.46), rng.uniform(18.43, 18.50)) for _ in range(24)] + [DEMO_END]
    feats = []
    for i, (x, y) in enumerate(pts, start=1):
        r = int((MARS_RADIUS_M * np.radians(y) - TRANSFORM.f) / TRANSFORM.e)
        c = int((MARS_RADIUS_M * np.radians(x) - TRANSFORM.c) / TRANSFORM.a)
        name = "Cheyava Falls (stub)" if i == 25 else f"Stub sample {i}"
        feats.append({"type": "Feature", "geometry": {"type": "Point", "coordinates": [x, y]},
                      "properties": {"sample_no": i, "name": name, "feature": f"Stub feature {i}",
                                     "type": "rock core", "sol_sealed": 100 * i, "rock_class": "stub",
                                     "location_method": "stub", "location_sol": 100 * i,
                                     "location_sol_gap": 0, "elev_m": round(float(z[r, c]), 2),
                                     "in_aoi": True, "source": "STUB"}})
    return {"type": "FeatureCollection", "features": feats}


def main(out_dir: Path) -> None:
    rng = np.random.default_rng(SEED)
    layers = make_terrain(rng)
    for name, rel in RASTER_PATHS.items():
        _write_tif(out_dir / rel, layers[name])
    meta = out_dir / "data/metadata"
    meta.mkdir(parents=True, exist_ok=True)
    (meta / "hazard_model.json").write_text(json.dumps(HAZARD_MODEL, indent=2))
    samples_path = out_dir / "frontend/public/data/samples.geojson"
    samples_path.parent.mkdir(parents=True, exist_ok=True)
    samples_path.write_text(json.dumps(make_samples(rng, layers["elevation"])))
    (out_dir / "data/STUB_DATA").write_text("synthetic data from backend/tools/make_stub_data.py\n")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit("usage: python -m backend.tools.make_stub_data <out_dir>")
    main(Path(sys.argv[1]))
